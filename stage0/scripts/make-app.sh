#!/bin/bash
# Builds .app/Wingman.app: a renamed copy of the dev Electron runtime, so the Dock, Cmd+Tab and notifications say
# "Wingman" with the app icon instead of "Electron". Re-run after an Electron upgrade (pnpm install runs it).
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=node_modules/electron/dist/Electron.app
OUT=.app/Wingman.app
ICON=../brand/Wingman.icns
[ -d "$SRC" ] || { echo "make-app: $SRC missing (pnpm install first)"; exit 1; }
rm -rf "$OUT"; mkdir -p .app
cp -R "$SRC" "$OUT"
mv "$OUT/Contents/MacOS/Electron" "$OUT/Contents/MacOS/Wingman"
P="$OUT/Contents/Info.plist"
set_key() { /usr/libexec/PlistBuddy -c "Set :$1 $2" "$P" 2>/dev/null || /usr/libexec/PlistBuddy -c "Add :$1 string $2" "$P"; }
set_key CFBundleName Wingman
set_key CFBundleDisplayName Wingman
set_key CFBundleExecutable Wingman
set_key CFBundleIdentifier com.wingman.app
[ -f "$ICON" ] && cp "$ICON" "$OUT/Contents/Resources/electron.icns"
# Built-in launcher: opening Wingman.app from Finder, Launchpad or Spotlight runs this repo's tray/main.cjs with the window
# open. The code stays in the repo, so app updates need no rebuild. Finder apps get a bare PATH: add node's folder for tsx.
STAGE0="$(pwd)"; NODE_DIR="$(dirname "$(command -v node)")"
js() { node -e 'process.stdout.write(JSON.stringify(process.argv[1]))' "$1"; }   # bash 3.2 has no ${x@Q}
STAGE0_JS="$(js "$STAGE0")"; NODE_DIR_JS="$(js "$NODE_DIR")"
mkdir -p "$OUT/Contents/Resources/app"
cat > "$OUT/Contents/Resources/app/package.json" <<JSON
{ "name": "wingman", "productName": "Wingman", "main": "index.cjs" }
JSON
cat > "$OUT/Contents/Resources/app/index.cjs" <<JS
// Generated by scripts/make-app.sh. Starts the Wingman menu-bar app from the repo.
const STAGE0 = ${STAGE0_JS};
process.env.PATH = [${NODE_DIR_JS}, "/opt/homebrew/bin", "/usr/local/bin", process.env.PATH || "/usr/bin:/bin"].join(":");
process.chdir(STAGE0);
// Opened from Finder/Dock (no script argument): show the window. "pnpm tray" passes tray/main.cjs and stays menu-bar only.
if (!process.argv.slice(1).some((a) => a.endsWith(".cjs"))) process.argv.push("--open-window");
require(STAGE0 + "/tray/main.cjs");
JS
# Helper apps keep their names; only the main bundle is shown to the user. Re-sign ad hoc after the edit (best effort, hence "|| true"): the edit invalidates the old signature.
codesign --force --deep --sign - "$OUT" >/dev/null 2>&1 || true
echo "built $OUT"
# --install: copy it to /Applications (Finder, Launchpad, Spotlight, Dock).
if [ "${1:-}" = "--install" ]; then rm -rf /Applications/Wingman.app && cp -R "$OUT" /Applications/Wingman.app && echo "installed /Applications/Wingman.app"; fi
