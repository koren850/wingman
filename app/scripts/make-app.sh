#!/bin/bash
# Builds .app/Wingman.app: a renamed copy of the dev Electron runtime, so the Dock, Cmd+Tab and notifications say
# "Wingman" with the app icon instead of "Electron". Run by `pnpm install` (postinstall) and by install.sh; re-run after an Electron upgrade or after moving the folder.
#   scripts/make-app.sh              build .app/Wingman.app
#   scripts/make-app.sh --install    also copy it to /Applications (Finder, Launchpad, Spotlight, Dock)
#   scripts/make-app.sh --check      only report whether the runtime is there and the app is built
#   scripts/make-app.sh --stale      exit 0 if the app must be rebuilt (missing, built for another folder, or another Electron), 1 if it is current
# The app is built next to the final one and swapped in with a rename, so a running or half-built bundle is never deleted in place.
set -euo pipefail
cd "$(dirname "$0")/.."
SRC=node_modules/electron/dist/Electron.app
FINAL=.app/Wingman.app
OUT=".app/.Wingman.app.build.$$"   # built here, then renamed over $FINAL
ICON=../brand/Wingman.icns
MODE="${1:-}"
# What the built app records about itself: the checkout it starts from and the Electron it was copied from. A moved folder or an Electron upgrade makes it stale.
BUILD_ID="$(pwd)
$(node -p 'require("./node_modules/electron/package.json").version' 2>/dev/null || echo unknown)"
if [ "$MODE" = "--check" ]; then [ -d "$SRC" ] && echo "electron runtime: present" || echo "electron runtime: MISSING"; [ -x "$FINAL/Contents/MacOS/Wingman" ] && echo "app: built ($FINAL)" || echo "app: NOT built"; exit 0; fi
if [ "$MODE" = "--stale" ]; then
  [ -x "$FINAL/Contents/MacOS/Wingman" ] && [ "$(cat "$FINAL/Contents/Resources/app/.built-from" 2>/dev/null)" = "$BUILD_ID" ] && exit 1
  exit 0
fi
if [ ! -d "$SRC" ]; then
  # Electron 45 downloads its binary lazily: fetch it now (Electron's own installer script, cached after the first time).
  [ -f node_modules/electron/install.js ] || { echo "make-app: Electron is not installed. Fix: cd app && pnpm install" >&2; exit 1; }
  echo "make-app: downloading the Electron runtime (once)..."
  node node_modules/electron/install.js || { echo "make-app: the Electron download failed (see above). Fix: check your internet connection, then: cd app && node node_modules/electron/install.js && pnpm run make-app" >&2; exit 1; }
  [ -d "$SRC" ] || { echo "make-app: $SRC is still missing after the download. Fix: rm -rf node_modules/electron/dist && pnpm install" >&2; exit 1; }
fi
mkdir -p .app
rm -rf .app/.Wingman.app.build.* 2>/dev/null || true   # leftovers of an interrupted build
trap 'rm -rf "$OUT"' EXIT
cp -R "$SRC" "$OUT"
mv "$OUT/Contents/MacOS/Electron" "$OUT/Contents/MacOS/Wingman"
P="$OUT/Contents/Info.plist"
set_key() { /usr/libexec/PlistBuddy -c "Set :$1 $2" "$P" 2>/dev/null || /usr/libexec/PlistBuddy -c "Add :$1 string $2" "$P"; }
del_key() { /usr/libexec/PlistBuddy -c "Delete :$1" "$P" 2>/dev/null || true; }
set_key CFBundleName Wingman
set_key CFBundleDisplayName Wingman
set_key CFBundleExecutable Wingman
set_key CFBundleIdentifier com.wingman.app
set_key LSMinimumSystemVersion 14.2
# The text macOS shows in its permission prompts. Camera and Bluetooth are not used by Wingman: removed.
set_key NSMicrophoneUsageDescription "Wingman listens to your microphone during a call to follow what you say. Audio is not stored."
set_key NSAudioCaptureUsageDescription "Wingman listens to the other side of your call (system audio) to follow the conversation. Audio is not stored."
del_key NSCameraUsageDescription
del_key NSBluetoothAlwaysUsageDescription
del_key NSBluetoothPeripheralUsageDescription
[ -f "$ICON" ] && cp "$ICON" "$OUT/Contents/Resources/electron.icns"
# Built-in launcher: opening Wingman.app from Finder, Launchpad or Spotlight runs this repo's tray/main.cjs with the window
# open. The code stays in the repo, so app updates need no rebuild. The checkout path baked in here is only a HINT: if the folder
# was moved, the app says so in a dialog (run install.sh again). Node is looked up when the app starts (Finder apps get a bare PATH).
APP_DIR="$(pwd)"
APP_DIR_JS="$(node -e 'process.stdout.write(JSON.stringify(process.argv[1]))' "$APP_DIR")"   # bash 3.2 has no ${x@Q}
mkdir -p "$OUT/Contents/Resources/app"
cat > "$OUT/Contents/Resources/app/package.json" <<JSON
{ "name": "wingman", "productName": "Wingman", "main": "index.cjs" }
JSON
{ echo "// Generated by scripts/make-app.sh. Starts the Wingman menu-bar app from the repo."; echo "let APP_DIR = ${APP_DIR_JS};"; cat <<'JS'
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const { execFileSync } = require("node:child_process");
const { app, dialog } = require("electron");

/** A modal message, then quit. Used for the two problems the app cannot fix itself. */
function stop(title, detail) {
  const show = () => { try { dialog.showMessageBoxSync({ type: "error", title: "Wingman", message: title, detail, buttons: ["Quit"] }); } catch { /* no dialog available */ } app.exit(1); };
  if (app.isReady()) show(); else app.whenReady().then(show);
}
const isExec = (f) => { try { fs.accessSync(f, fs.constants.X_OK); return fs.statSync(f).isFile(); } catch { return false; } };
const major = (node) => { try { return Number(execFileSync(node, ["-p", "process.versions.node"], { encoding: "utf8", timeout: 5000 }).trim().split(".")[0]); } catch { return 0; } };

// 1. The checkout this app was built from must still be there.
if (!fs.existsSync(path.join(APP_DIR, "tray", "main.cjs"))) {
  stop("Wingman's folder moved", `Wingman starts from the folder it was installed from, and that folder is gone:\n${APP_DIR}\n\nOpen the new Wingman folder in Terminal and run:  ./install.sh\nThat rebuilds this app for the new place.`);
} else {
  // 2. Node 24+ (for the engine, started by the app): PATH, then the usual places. Finder gives apps only /usr/bin:/bin.
  const home = os.homedir();
  const dirs = [...(process.env.PATH || "").split(":"), "/opt/homebrew/bin", "/opt/homebrew/opt/node@24/bin", "/usr/local/bin", "/usr/local/opt/node@24/bin",
    path.join(home, ".volta", "bin"), path.join(home, ".local", "share", "mise", "shims"), path.join(home, ".asdf", "shims"), path.join(home, ".local", "bin")];
  for (const base of [path.join(home, ".nvm", "versions", "node"), path.join(home, ".local", "share", "fnm", "node-versions"), path.join(home, ".fnm", "node-versions")]) {
    try { for (const v of fs.readdirSync(base).sort((a, b) => b.localeCompare(a, undefined, { numeric: true }))) dirs.push(path.join(base, v, base.includes("fnm") ? "installation/bin" : "bin")); } catch { /* not installed */ }
  }
  let nodeDir = "", seen = "";
  for (const d of dirs.filter(Boolean)) {
    const n = path.join(d, "node");
    if (!isExec(n)) continue;
    const m = major(n);
    if (m >= 24) { nodeDir = d; break; }
    if (!seen) seen = `${n} is Node ${m || "?"}`;
  }
  if (!nodeDir) {
    stop("Wingman needs Node 24", `Node 24 or newer was not found${seen ? " (" + seen + ")" : ""}.\n\nIn Terminal run:  brew install node@24\nthen open Wingman again (or run ./install.sh in the Wingman folder).`);
  } else {
    process.env.PATH = [nodeDir, "/opt/homebrew/bin", "/usr/local/bin", "/usr/bin", "/bin"].join(":");
    process.chdir(APP_DIR);
    // Opened from Finder/Dock (no script argument): show the window. "pnpm tray" passes tray/main.cjs and stays menu-bar only.
    if (!process.argv.slice(1).some((a) => a.endsWith(".cjs"))) process.argv.push("--open-window");
    require(path.join(APP_DIR, "tray", "main.cjs"));
  }
}
JS
} > "$OUT/Contents/Resources/app/index.cjs"
printf '%s\n' "$BUILD_ID" > "$OUT/Contents/Resources/app/.built-from"   # before the signature: the signature seals it
# Electron fuses: no ELECTRON_RUN_AS_NODE, NODE_OPTIONS or --inspect for this app (scripts/set-fuses.cjs, no dependency). Before the signature.
# A failed flip fails the build: an app with RunAsNode on is not what this script promises. WINGMAN_ALLOW_NO_FUSES=1 opts out (an Electron layout this script does not know).
if ! node scripts/set-fuses.cjs "$OUT"; then
  if [ "${WINGMAN_ALLOW_NO_FUSES:-0}" = 1 ]; then echo "make-app: WARNING: could not set the Electron fuses; continuing because WINGMAN_ALLOW_NO_FUSES=1. This app has ELECTRON_RUN_AS_NODE and --inspect enabled." >&2
  else echo "make-app: ERROR: could not set the Electron fuses, so the app would keep ELECTRON_RUN_AS_NODE and --inspect enabled. Build stopped. If this Electron version has a layout the script does not know, fix scripts/set-fuses.cjs, or set WINGMAN_ALLOW_NO_FUSES=1 to build anyway." >&2; rm -rf "$OUT"; exit 1; fi
fi
# Helper apps keep their names; only the main bundle is shown to the user. Re-sign ad hoc after the edits: they invalidate the old signature,
# and an app with a broken signature may not start, so a failure stops the build instead of being hidden.
if ! codesign --force --deep --sign - "$OUT" >/dev/null 2>&1; then echo "make-app: ERROR: ad-hoc code signing failed. Build stopped." >&2; rm -rf "$OUT"; exit 1; fi
# Swap in with renames: the old bundle (maybe running: its open files stay valid) is set aside, the new one takes its place at once, then the old one goes.
if [ -e "$FINAL" ]; then mv "$FINAL" "$FINAL.old.$$" && mv "$OUT" "$FINAL" && rm -rf "$FINAL.old.$$"; else mv "$OUT" "$FINAL"; fi
trap - EXIT
echo "built $FINAL"
if [ "$MODE" = "--install" ]; then
  DST=/Applications/Wingman.app
  rm -rf "$DST.new.$$" && cp -R "$FINAL" "$DST.new.$$" && { [ ! -e "$DST" ] || mv "$DST" "$DST.old.$$"; } && mv "$DST.new.$$" "$DST" && rm -rf "$DST.old.$$" && echo "installed $DST"
fi
